"""
GeM search keywords derived from company offering profiles.

Every ready company profile contributes search terms, from three places:
  - auto keywords: generated by the LLM from the profile's own offerings / capabilities (each one must
    trace back to a profile entry; excluded capabilities and generic-only terms are dropped; every
    offering gets at least one term). Regenerated whenever the offering profile changes.
  - the company's own keywords (editable list `tender_search_keywords`) - never overwritten.
  - learned keywords: GeM item categories of the company's good matches.
The scraper runs GeM's keyword search with them, each company with its own budget, keywords that found
good tenders first. Nothing here is specific to any company or industry.
"""

from __future__ import annotations

import asyncio
from datetime import datetime, timezone
from typing import Any, Dict, Iterable, List, Optional

from motor.motor_asyncio import AsyncIOMotorDatabase

from app.config import settings
from app.services.matching_utils import (
    _FILLER_WORDS,
    _stem,
    all_tokens,
    normalize_text,
    significant_tokens,
)
from app.services.relevance_service import COMPANY_PROFILE_KEYS, profile_version
from app.utils.logger import get_logger

logger = get_logger(__name__)

MAX_KEYWORD_WORDS = 4
MAX_AUTO_KEYWORDS = 30
DEAD_AFTER_RUNS = 3  # searched this many times without a single good match -> moved to the back
MAX_MATCHED_BIDS = 50
MAX_KEYWORD_STATS = 200

# Profile entries a keyword may come from, and the ones that must each get at least one keyword.
SOURCE_FIELDS = ("offerings", "core_capabilities", "capabilities", "technologies", "domains")
COVERAGE_FIELDS = ("offerings", "core_capabilities")


def _clean(keywords: Iterable[Any]) -> List[str]:
    seen = set()
    out: List[str] = []
    for keyword in keywords or []:
        text = " ".join(str(keyword).split())
        norm = normalize_text(text)
        if not norm or len(norm.split()) > MAX_KEYWORD_WORDS or norm in seen:
            continue
        seen.add(norm)
        out.append(text)
    return out


def _entries(meta: Dict[str, Any], fields: Iterable[str]) -> List[str]:
    out: List[str] = []
    for field in fields:
        value = meta.get(field)
        if isinstance(value, str):
            value = [value]
        for item in value or []:
            text = " ".join(str(item).split()) if isinstance(item, (str, int, float)) else ""
            if text and text not in out:
                out.append(text)
    return out


# ---------------------------------------------------------------- listing filter

CUSTOM_SERVICE_PREFIX = "custom bid for service"


# Words a bid card often leaves out without changing what is bought ("Machine Learning Services" is the
# same purchase as "Machine Learning ..."), so they are not required on the card. Grammatical filler
# ("of", "for", ...) is never required either. Every other keyword word is.
_OPTIONAL_CARD_WORDS = {
    "service", "solution", "software", "platform", "development", "implementation", "support",
    "based", "custom", "new", "it", "technology", "tech", "digital", "provision", "providing", "provider",
    "integrated", "advanced", "smart", "complete", "comprehensive", "general", "various", "related",
    "including", "end",
}


def keyword_matches_listing(keyword: str, listing_text: Optional[str]) -> bool:
    """
    Decide whether a GeM keyword-search hit is worth downloading and analysing.

    GeM's search matches any word anywhere in the bid documents ("artificial intelligence" also
    returns "ARTIFICIAL FLOWER"; "Deployment of LLM" returns "Deployment of technical manpower").
    Keep a hit when:
      - every meaningful word of the keyword is on the card ("deployment" AND "llm"; "learning" AND
        "management" AND "system"), compared in singular form; GeM truncates item text, so the
        cut-off last word may match as a prefix ("Machi..." for "machine"), or
      - it is a GeM "Custom Bid for Services", whose real scope is only in the bid document.
    """
    raw = listing_text or ""
    truncated = raw.rstrip().endswith("...")
    text = normalize_text(raw.replace("...", " "))
    if not text:
        return True  # nothing to check against; let analysis decide
    if text.startswith(CUSTOM_SERVICE_PREFIX):
        return True

    words = [_stem(w) for w in text.split()]
    last = words[-1]
    tokens = [_stem(w) for w in normalize_text(keyword).split() if w not in _FILLER_WORDS]
    required = [t for t in tokens if t not in _OPTIONAL_CARD_WORDS] or tokens
    if not required:
        return False

    def on_card(part: str) -> bool:
        return part in words or (truncated and len(last) >= 3 and part.startswith(last))

    return all(on_card(part) for part in required)


# ------------------------------------------------------------ auto keywords

def _trace(source: Optional[str], keyword: str, entries: List[str]) -> Optional[str]:
    """The profile entry a keyword comes from, or None if it cannot be traced to the profile."""
    if source:
        src = all_tokens(source)
        if src:
            for entry in entries:
                tokens = all_tokens(entry)
                if tokens and (src <= tokens or tokens <= src):
                    return entry
        return None
    # Older output without "from": the keyword itself must share a specific word with an entry.
    words = significant_tokens(keyword)
    for entry in entries:
        if words & significant_tokens(entry):
            return entry
    return None


def _is_excluded(keyword: str, excluded: List[str]) -> bool:
    tokens = all_tokens(keyword)
    for phrase in excluded:
        ex = all_tokens(phrase)
        if ex and tokens and (ex <= tokens or tokens <= ex):
            return True
    return False


def build_auto_keywords(meta: Dict[str, Any], suggestions: Iterable[Any]) -> List[Dict[str, str]]:
    """
    Validate LLM keyword suggestions against the company's own profile:
      - each keyword must trace back to an offering / capability entry,
      - nothing that hits an excluded capability, nothing generic-only, at most 4 words,
      - every offering and core capability gets at least one keyword (its own name as a fallback).
    Returns [{"keyword", "from"}].
    """
    entries = _entries(meta, SOURCE_FIELDS)
    excluded = _entries(meta, ("excluded_capabilities",))
    out: List[Dict[str, str]] = []
    seen: set = set()
    covered: set = set()

    def add(keyword: Any, source: str) -> None:
        text = " ".join(str(keyword or "").split())
        norm = normalize_text(text)
        if not norm or norm in seen or len(norm.split()) > MAX_KEYWORD_WORDS:
            return
        if not significant_tokens(text) or _is_excluded(text, excluded):
            return
        seen.add(norm)
        covered.add(normalize_text(source))
        out.append({"keyword": text, "from": source})

    for suggestion in suggestions or []:
        if isinstance(suggestion, dict):
            keyword, source = suggestion.get("keyword"), suggestion.get("from")
        else:
            keyword, source = suggestion, None
        entry = _trace(source, str(keyword or ""), entries)
        if entry:
            add(keyword, entry)

    for entry in _entries(meta, COVERAGE_FIELDS):
        if normalize_text(entry) not in covered:
            add(entry, entry)  # uncovered offering: search for its own name

    return out[:MAX_AUTO_KEYWORDS]


async def generate_auto_keywords(
    db: AsyncIOMotorDatabase, profile: Dict[str, Any], llm: Any = None
) -> List[Dict[str, str]]:
    """Generate, validate and store the profile's auto keywords."""
    meta = profile.get("metadata") or {}
    company = {k: meta.get(k) for k in COMPANY_PROFILE_KEYS if meta.get(k)}
    company.setdefault("company_name", profile.get("name"))
    llm_ok = True
    try:
        if llm is None:
            from app.processors.llm_extractor import LLMExtractor

            llm = LLMExtractor()
        suggestions = await asyncio.to_thread(llm.suggest_search_keywords, company)
    except Exception as exc:
        logger.info("search_keywords.generate_failed", company_id=profile.get("company_id"), error=str(exc))
        suggestions, llm_ok = [], False

    auto = build_auto_keywords(meta, suggestions)
    # Version marks the profile these were built from; on an LLM failure it stays unset so the
    # next scrape tries again (meanwhile the offerings' own names are searched).
    await db.get_collection("company_profiles").update_one(
        {"company_id": profile.get("company_id")},
        {
            "$set": {
                "metadata.auto_search_keywords": auto,
                "metadata.auto_search_keywords_version": profile_version(profile) if llm_ok else None,
            }
        },
    )
    meta["auto_search_keywords"] = auto
    return auto


def all_profile_keywords(meta: Dict[str, Any]) -> List[str]:
    """Learned + the company's own + auto keywords, de-duplicated."""
    auto = [a.get("keyword") for a in meta.get("auto_search_keywords") or [] if isinstance(a, dict)]
    return _clean(
        list(meta.get("learned_search_keywords") or [])
        + list(meta.get("tender_search_keywords") or [])
        + auto
    )


def rank_keywords(keywords: List[str], stats: Optional[List[Dict[str, Any]]]) -> List[str]:
    """
    Productive keywords (found good matches) first, most matches first; then new / little-tried ones,
    least-searched first (so the budget rotates through them); keywords that never found a good
    match after DEAD_AFTER_RUNS searches go last.
    """
    by_keyword = {normalize_text(s.get("keyword")): s for s in stats or [] if isinstance(s, dict)}

    def order(item):
        index, keyword = item
        stat = by_keyword.get(normalize_text(keyword)) or {}
        matched = len(stat.get("matched_bids") or [])
        runs = int(stat.get("runs") or 0)
        last_run = str(stat.get("last_run") or "")
        if matched:
            return (0, -matched, "", index)
        if runs < DEAD_AFTER_RUNS:
            return (1, runs, last_run, index)
        return (2, 0, last_run, index)

    return [keyword for _, keyword in sorted(enumerate(keywords), key=order)]


async def ensure_profile_keywords(db: AsyncIOMotorDatabase, profile: Dict[str, Any], llm: Any = None) -> List[str]:
    """
    The profile's GeM search keywords, best first. Auto keywords are (re)generated when missing or
    when the offering profile changed since they were built.
    """
    meta = profile.get("metadata") or {}
    if not meta.get("auto_search_keywords") or meta.get("auto_search_keywords_version") != profile_version(profile):
        await generate_auto_keywords(db, profile, llm=llm)
    return rank_keywords(all_profile_keywords(meta), meta.get("keyword_stats"))


async def collect_search_keywords(
    db: AsyncIOMotorDatabase, limit: int, llm: Any = None, per_company: Optional[int] = None
) -> List[str]:
    """Keywords from all ready company profiles: each company its own budget, interleaved, overall cap."""
    per_company = per_company or settings.SCRAPE_KEYWORDS_PER_COMPANY
    per_profile: List[List[str]] = []
    cursor = db.get_collection("company_profiles").find({"status.processing_status": "ready"})
    async for profile in cursor:
        if profile.get("metadata"):
            keywords = await ensure_profile_keywords(db, profile, llm=llm)
            per_profile.append(keywords[:per_company])

    merged: List[str] = []
    seen = set()
    index = 0
    while len(merged) < limit and any(index < len(kws) for kws in per_profile):
        for kws in per_profile:
            if index < len(kws):
                norm = normalize_text(kws[index])
                if norm not in seen:
                    seen.add(norm)
                    merged.append(kws[index])
                    if len(merged) >= limit:
                        break
        index += 1
    return merged


def listing_relevant(listing_text: Optional[str], keywords: List[str]) -> bool:
    """
    Is a bid from GeM's general newest-first listing worth analysing? Only when its card matches one
    of the companies' own keywords (same rule as keyword-search hits) or it is a Custom Bid for
    Services, whose scope is only in the document. Saves an LLM call per irrelevant bid.
    """
    text = normalize_text((listing_text or "").replace("...", " "))
    if not text or text.startswith(CUSTOM_SERVICE_PREFIX):
        return True
    return any(keyword_matches_listing(keyword, listing_text) for keyword in keywords)


QUIET_AFTER_RUNS = 2  # searched this often without keeping a single bid -> only page 1 next time


async def quiet_keywords(db: AsyncIOMotorDatabase) -> set:
    """Normalized keywords that kept no bid in their recent searches (searched one page deep)."""
    quiet = set()
    async for profile in db.get_collection("company_profiles").find({"status.processing_status": "ready"}):
        for stat in (profile.get("metadata") or {}).get("keyword_stats") or []:
            if (
                isinstance(stat, dict)
                and int(stat.get("runs") or 0) >= QUIET_AFTER_RUNS
                and not stat.get("found")
                and not stat.get("matched_bids")
            ):
                quiet.add(normalize_text(stat.get("keyword")))
    return quiet


# ------------------------------------------------------------ keyword yield

async def record_keyword_yield(db: AsyncIOMotorDatabase, hits: Dict[str, List[str]], new_run: bool = True) -> None:
    """
    For every company that owns a searched keyword, store how many GeM bids it found and which of them
    are good matches (score >= MATCH_MIN_SCORE) for that company.
    Called right after the searches (new_run=True: counts the run, records "found") and again at the end
    of the scrape once the new bids are analysed and judged (new_run=False: only updates "matched").
    """
    from app.services.relevance_service import RelevanceService, build_match, cosine_similarity

    if not hits:
        return
    bid_ids = sorted({bid for ids in hits.values() for bid in ids})
    tenders: Dict[str, Dict[str, Any]] = {}
    if bid_ids:
        async for tender in db.get_collection("tenders").find({"bid_id": {"$in": bid_ids}}):
            tenders[tender.get("bid_id")] = tender

    now = datetime.now(timezone.utc).isoformat()
    relevance = RelevanceService(db)
    profiles = db.get_collection("company_profiles")
    async for profile in profiles.find({"status.processing_status": "ready"}):
        meta = profile.get("metadata") or {}
        own = {normalize_text(k) for k in all_profile_keywords(meta)}
        searched = {k: ids for k, ids in hits.items() if normalize_text(k) in own}
        if not searched:
            continue

        judgments = await relevance.get_judgments(profile.get("company_id"), profile)
        embedding = profile.get("summary_embedding") or []
        stats = {normalize_text(s.get("keyword")): dict(s) for s in meta.get("keyword_stats") or [] if isinstance(s, dict)}
        for keyword, ids in searched.items():
            stat = stats.setdefault(normalize_text(keyword), {"keyword": keyword, "runs": 0, "matched_bids": []})
            if new_run or not stat.get("runs"):
                stat["runs"] = int(stat.get("runs") or 0) + 1
                stat["last_run"] = now
            stat["found"] = len(ids)
            matched = list(stat.get("matched_bids") or [])
            for bid in ids:
                tender = tenders.get(bid)
                if not tender or bid in matched:
                    continue
                judgment = relevance.valid_judgment(judgments.get(str(tender.get("_id"))), tender)
                if not judgment:
                    continue
                vector = cosine_similarity(embedding, tender.get("summary_embedding") or [])
                if build_match(tender, profile, vector, judgment)["score"] >= settings.MATCH_MIN_SCORE:
                    matched.append(bid)
            stat["matched_bids"] = matched[-MAX_MATCHED_BIDS:]
            stat["matched"] = len(stat["matched_bids"])

        ordered = sorted(stats.values(), key=lambda s: str(s.get("last_run") or ""), reverse=True)
        await profiles.update_one(
            {"company_id": profile.get("company_id")},
            {"$set": {"metadata.keyword_stats": ordered[:MAX_KEYWORD_STATS]}},
        )
